import sys
import unittest
from pathlib import Path

sys.dont_write_bytecode = True
SCRIPTS = Path(__file__).resolve().parents[1] / "skills" / "delivery-video" / "scripts"
sys.path.insert(0, str(SCRIPTS))
import dv_notes  # noqa: E402

ISSUE = {
    "id": "BUG-1",
    "title": "Save keeps old total",
    "severity": "major",
    "environment": "staging",
    "expected": "The new total appears",
    "actual": "The old total remains",
    "repro": ["Open the order", "Change the amount", "Save"],
}
SEGMENTS = [
    {"id": "01-repro", "phase": "repro", "shot": "take-01.mp4", "start": 0.5, "end": 11.0},
    {"id": "02-actual", "phase": "actual", "shot": "take-02.mp4", "start": 1.0, "end": 9.0},
]
TIMELINE = [
    {"id": "01-repro", "kind": "shot", "start": 0.0, "end": 7.3, "speed": 0.7,
     "source": "take-01.mp4", "source_start": 0.5, "source_end": 11.0},
    {"id": "02-actual", "kind": "shot", "start": 7.3, "end": 12.5, "speed": 1.1,
     "source": "take-02.mp4", "source_start": 0.5, "source_end": 9.0},
]
REPORT = {
    "duration_s": 12.5,
    "video_sha256": "abc123",
    "status": "pass",
    "profile": "delivery-v1",
    "score": {"total": 100},
}


class FeedbackNoteTests(unittest.TestCase):
    def test_markdown_carries_the_issue_and_timeline(self):
        markdown = dv_notes.feedback_markdown(ISSUE, SEGMENTS, TIMELINE, REPORT)

        self.assertIn("# BUG-1 Save keeps old total", markdown)
        self.assertIn("- Severity: `major` (P2 MAJOR)", markdown)
        self.assertIn("1. Open the order", markdown)
        self.assertIn("3. Save", markdown)
        self.assertIn("| REPRO | 00:00.000-00:07.300 | `take-01.mp4` | 0.50-11.00s | 0.70x |",
                      markdown)
        self.assertIn("Every shot segment is one continuous range", markdown)
        self.assertIn("SHA256 `abc123`", markdown)
        self.assertIn("Draft generated by render.py", markdown)

    def test_payload_records_phases_ranges_and_the_artifact_hash(self):
        payload = dv_notes.feedback_payload(ISSUE, SEGMENTS, REPORT)

        self.assertEqual(payload["artifact"]["sha256"], "abc123")
        self.assertEqual([item["phase"] for item in payload["segments"]], ["repro", "actual"])
        self.assertEqual(payload["segments"][1]["start"], 1.0)

    def test_markdown_cells_cannot_break_the_table(self):
        timeline = [dict(TIMELINE[0], source="take|01\n.mp4")]

        markdown = dv_notes.feedback_markdown(ISSUE, SEGMENTS, timeline, REPORT)

        self.assertIn("`take\\|01 .mp4`", markdown)


class DeliveryNoteTests(unittest.TestCase):
    REPORT = {
        "duration_s": 7.3, "video_sha256": "abc123", "status": "pass", "profile": "delivery-v1",
        "score": {"total": 96}, "episode": {"sha256": "ep"}, "timeline": {"sha256": "tl"},
        "warnings": [{"code": "T301", "message": "longest freeze span 0.9s"}],
    }
    TIMELINE = [{"id": "05-wait", "kind": "shot", "label": "等待", "case": "F-02", "start": 0.0,
                 "end": 7.3, "source": "take-02.mp4", "source_start": 0.5, "source_end": 11.0,
                 "speed": 2.35}]

    def test_rows_retime_notes_and_evidence_come_from_the_rendered_facts(self):
        episode = {"title": "订单演示", "evidence": {"git_sha": "abc1234", "tickets": ["T-1", "T-2"]}}

        text = dv_notes.delivery_markdown(episode, self.TIMELINE, self.REPORT,
                                          [{"id": "05-wait", "speed": 2.35}])

        self.assertIn("# 订单演示", text)
        self.assertIn("SHA256 `abc123`", text)
        self.assertIn("- git_sha: abc1234", text)
        self.assertIn("- tickets: T-1, T-2", text)
        self.assertIn("| 1 | F-02 | 等待 | 00:00.000-00:07.300 | `take-02.mp4` "
                      "| 0.50-11.00s | 2.35x |", text)
        self.assertIn("05-wait plays at 2.35x (footage fast-forwarded)", text)
        self.assertIn("- `T301`: longest freeze span 0.9s", text)

    def test_a_slowed_segment_is_named_as_slowed_down(self):
        text = dv_notes.delivery_markdown({}, self.TIMELINE, self.REPORT,
                                          [{"id": "05-wait", "speed": 0.6}])
        self.assertIn("plays at 0.60x (footage slowed down)", text)


if __name__ == "__main__":
    unittest.main()
