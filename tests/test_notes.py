import sys
import unittest
from pathlib import Path

sys.dont_write_bytecode = True
SCRIPTS = Path(__file__).resolve().parents[1] / "skills" / "delivery-video" / "scripts"
sys.path.insert(0, str(SCRIPTS))
import dv_notes  # noqa: E402

ISSUE = {
    "id": "BUG-1",
    "title": "Save keeps old total",
    "severity": "major",
    "environment": "staging",
    "expected": "The new total appears",
    "actual": "The old total remains",
    "repro": ["Open the order", "Change the amount", "Save"],
}
SEGMENTS = [
    {"id": "01-repro", "phase": "repro", "shot": "take-01.mp4", "start": 0.5, "end": 11.0},
    {"id": "02-actual", "phase": "actual", "shot": "take-02.mp4", "start": 1.0, "end": 9.0},
]
TIMELINE = [
    {"id": "01-repro", "start": 0.0, "end": 7.3,
     "source": "take-01.mp4", "source_start": 0.5, "source_end": 11.0},
    {"id": "02-actual", "start": 7.3, "end": 12.5,
     "source": "take-02.mp4", "source_start": 0.5, "source_end": 9.0},
]
REPORT = {
    "duration_s": 12.5,
    "video_sha256": "abc123",
    "status": "pass",
    "profile": "delivery-v1",
    "score": {"total": 100},
}


class FeedbackNoteTests(unittest.TestCase):
    def test_markdown_carries_the_issue_and_timeline(self):
        markdown = dv_notes.feedback_markdown(ISSUE, SEGMENTS, TIMELINE, REPORT)

        self.assertIn("# BUG-1 Save keeps old total", markdown)
        self.assertIn("- Severity: `major` (P2 MAJOR)", markdown)
        self.assertIn("1. Open the order", markdown)
        self.assertIn("3. Save", markdown)
        self.assertIn("| REPRO | 00:00.000-00:07.300 | `take-01.mp4` | 0.50-11.00s |", markdown)
        self.assertIn("SHA256 `abc123`", markdown)
        self.assertIn("Draft generated by render.py", markdown)

    def test_payload_records_phases_ranges_and_the_artifact_hash(self):
        payload = dv_notes.feedback_payload(ISSUE, SEGMENTS, REPORT)

        self.assertEqual(payload["artifact"]["sha256"], "abc123")
        self.assertEqual([item["phase"] for item in payload["segments"]], ["repro", "actual"])
        self.assertEqual(payload["segments"][1]["start"], 1.0)

    def test_markdown_cells_cannot_break_the_table(self):
        timeline = [dict(TIMELINE[0], source="take|01\n.mp4")]

        markdown = dv_notes.feedback_markdown(ISSUE, SEGMENTS, timeline, REPORT)

        self.assertIn("`take\\|01 .mp4`", markdown)


if __name__ == "__main__":
    unittest.main()
